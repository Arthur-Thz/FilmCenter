create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null default '',
  foto_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.genres (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.movies (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  year integer not null check (year between 1888 and 2100),
  director text not null default '',
  duration integer check (duration is null or duration > 0),
  rating numeric(2,1) check (rating is null or rating between 0 and 5),
  status text not null default 'want_to_watch' check (status in ('watched','want_to_watch','watching')),
  favorite boolean not null default false,
  image_url text,
  trailer_url text,
  genre_id bigint references public.genres(id) on delete set null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists movies_user_id_idx on public.movies(user_id);
create index if not exists movies_genre_id_idx on public.movies(genre_id);
create index if not exists movies_title_idx on public.movies using gin (to_tsvector('portuguese', title));

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nome) values (new.id, coalesce(new.raw_user_meta_data->>'nome', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.genres enable row level security;
alter table public.movies enable row level security;

drop policy if exists "profile owner select" on public.profiles;
create policy "profile owner select" on public.profiles for select using (auth.uid() = id);
drop policy if exists "profile owner update" on public.profiles;
create policy "profile owner update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists "profile owner insert" on public.profiles;
create policy "profile owner insert" on public.profiles for insert with check (auth.uid() = id);

drop policy if exists "authenticated read genres" on public.genres;
create policy "authenticated read genres" on public.genres for select to authenticated using (true);
drop policy if exists "owner select movies" on public.movies;
create policy "owner select movies" on public.movies for select to authenticated using (auth.uid() = user_id);
drop policy if exists "owner insert movies" on public.movies;
create policy "owner insert movies" on public.movies for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "owner update movies" on public.movies;
create policy "owner update movies" on public.movies for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "owner delete movies" on public.movies;
create policy "owner delete movies" on public.movies for delete to authenticated using (auth.uid() = user_id);

grant usage on schema public to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select on public.genres to authenticated;
grant select, insert, update, delete on public.movies to authenticated;

grant usage, select on all sequences in schema public to authenticated;

